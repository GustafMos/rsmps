// Build helper for the headless renderer (src/cli2).
//
//   node scripts/build-cli.mjs gen     write src/cli2/generated-nodes.ts (static import list of every built-in node)
//   node scripts/build-cli.mjs         gen + bundle src/cli2/main.ts into dist-cli/rsmps.mjs with esbuild
//
// Why a generated list instead of Vite's import.meta.glob: the glob only exists inside Vite/Vitest, so
// the CLI would need a Vite runtime (vite-node / SSR build) even for development. A plain static import
// list works unchanged under tsx, esbuild and Vitest, adds no runtime dependency, and cannot go stale
// because it is regenerated by `npm run cli2` and `npm run build:cli2` (src/cli2/generated-nodes.ts is
// a build artifact: do not edit or commit it).
import { readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const nodesDir = join(root, 'src/engine/nodes');
const outFile = join(root, 'src/cli2/generated-nodes.ts');

function walk(dir) {
  const files = [];
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) files.push(...walk(p));
    else if (name.endsWith('.node.ts')) files.push(p);
  }
  return files;
}

export function generate() {
  const files = walk(nodesDir).map((f) => relative(join(root, 'src/cli2'), f).replace(/\\/g, '/'));
  const lines = [
    '// @ts-nocheck (imports carry .ts: the .node suffix defeats extension probing in Node resolvers)',
    '// GENERATED by scripts/build-cli.mjs from src/engine/nodes/**/*.node.ts. Do not edit or commit.',
    ...files.map((f, i) => `import * as m${i} from '${f.startsWith('.') ? f : './' + f}';`),
    '',
    `export const nodeModules: Record<string, unknown>[] = [${files.map((_, i) => `m${i}`).join(', ')}];`,
    `export const nodeFiles: string[] = ${JSON.stringify(files.map((f) => f.replace(/^.*\/nodes\//, '')))};`,
    '',
  ];
  writeFileSync(outFile, lines.join('\n'));
  return files.length;
}

const cmd = process.argv[2] ?? 'build';
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const n = generate();
  if (cmd === 'gen') {
    console.log(`generated ${relative(root, outFile)} (${n} node files)`);
  } else {
    const { build } = await import('esbuild');
    mkdirSync(join(root, 'dist-cli'), { recursive: true });
    await build({
      entryPoints: [join(root, 'src/cli2/main.ts')],
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node20',
      outfile: join(root, 'dist-cli/rsmps.mjs'),
      external: ['sharp', 'webgpu', '@ffmpeg-installer/ffmpeg'],
      banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
      logLevel: 'info',
    });
    console.log(`built dist-cli/rsmps.mjs (${n} node files). Run: node dist-cli/rsmps.mjs --help`);
  }
}
