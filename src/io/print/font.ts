export const FONT_ADVANCE = 6;
export const FONT_HEIGHT = 7;

/** Glyph for a character (blank for unknown ones). Returns 5 column bytes. */
export function glyph(ch: string): number[] {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS[' '];
}

/** Width of `text` in font pixels (no trailing gap). */
export function textWidthPx(text: string): number {
  return text.length === 0 ? 0 : text.length * FONT_ADVANCE - 1;
}
