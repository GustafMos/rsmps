import type { Registry } from '../../engine/define';
import type { GraphDoc } from '../../engine/types';
import { layoutFor } from './layout';

const GAP_X = 90;
const GAP_Y = 28;

/** Simple left-to-right layered layout. Positions only the given ids (default: all). */
export function autoLayout(graph: GraphDoc, registry: Registry, only?: ReadonlySet<string>): GraphDoc {
  const targets = graph.nodes.filter((n) => !only || only.has(n.id));
  if (!targets.length) return graph;
  const ids = new Set(targets.map((n) => n.id));
  const preds = new Map<string, string[]>();
  for (const n of targets) preds.set(n.id, []);
  for (const e of graph.edges) if (ids.has(e.from.node) && ids.has(e.to.node)) preds.get(e.to.node)!.push(e.from.node);

  const layer = new Map<string, number>();
  const visiting = new Set<string>();
  const depth = (id: string): number => {
    const known = layer.get(id);
    if (known !== undefined) return known;
    if (visiting.has(id)) return 0;
    visiting.add(id);
    let d = 0;
    for (const p of preds.get(id) ?? []) d = Math.max(d, depth(p) + 1);
    visiting.delete(id);
    layer.set(id, d);
    return d;
  };
  targets.forEach((n) => depth(n.id));

  const cols: string[][] = [];
  for (const n of targets) (cols[layer.get(n.id)!] ??= []).push(n.id);

  const byId = new Map(graph.nodes.map((n) => [n.id, n]));
  const height = (id: string) => {
    const n = byId.get(id)!;
    return layoutFor(graph, n, registry.get(n.type)).height;
  };
  const originX = Math.min(...targets.map((n) => n.x));
  const originY = Math.min(...targets.map((n) => n.y));
  const pos = new Map<string, { x: number; y: number }>();
  let x = originX;
  cols.forEach((col) => {
    if (!col) return;
    // order by mean predecessor y so wires stay short
    col.sort((a, b) => mean(preds.get(a)!, pos) - mean(preds.get(b)!, pos));
    let y = originY;
    let colW = 0;
    for (const id of col) {
      pos.set(id, { x, y });
      y += height(id) + GAP_Y;
      colW = Math.max(colW, layoutFor(graph, byId.get(id)!, registry.get(byId.get(id)!.type)).width);
    }
    x += colW + GAP_X;
  });
  return { ...graph, nodes: graph.nodes.map((n) => (pos.has(n.id) ? { ...n, ...pos.get(n.id)! } : n)) };
}

function mean(ids: string[], pos: Map<string, { x: number; y: number }>): number {
  const ys = ids.map((i) => pos.get(i)?.y).filter((v): v is number => v !== undefined);
  return ys.length ? ys.reduce((a, b) => a + b, 0) / ys.length : 0;
}

/** True when the document carries no usable positions (e.g. generated by a script). */
export function needsLayout(graph: GraphDoc): boolean {
  if (graph.nodes.length < 2) return false;
  if (graph.nodes.some((n) => !Number.isFinite(n.x) || !Number.isFinite(n.y))) return true;
  const first = graph.nodes[0];
  return graph.nodes.every((n) => n.x === first.x && n.y === first.y);
}
